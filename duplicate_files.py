"""
Duplicate File Detection Program
=================================
A practical Python program that scans a specified directory and all its subdirectories
to detect duplicate files by computing and comparing their cryptographic SHA-256 hash values.
"""

import os
import hashlib
import sys


def calculate_hash(file_path, chunk_size=65536):
    """
    Calculate the SHA-256 cryptographic hash of a file.

    Parameters:
        file_path (str): Path to the target file.
        chunk_size (int): Byte size of chunks read during each iteration (default: 64 KB).

    Returns:
        str: 64-character hexadecimal SHA-256 digest string, or None if reading fails.
    """
    sha256_hasher = hashlib.sha256()
    try:
        with open(file_path, "rb") as file_handle:
            while True:
                data_chunk = file_handle.read(chunk_size)
                if not data_chunk:
                    break
                sha256_hasher.update(data_chunk)
        return sha256_hasher.hexdigest()
    except (PermissionError, FileNotFoundError, OSError):
        return None


def format_storage_size(size_bytes):
    """
    Convert a raw byte count into a formatted human-readable string.

    Parameters:
        size_bytes (int): Total size in bytes.

    Returns:
        str: Formatted string (Bytes, KB, MB, or GB).
    """
    if size_bytes < 1024:
        return f"{size_bytes} Bytes"
    elif size_bytes < 1024 * 1024:
        return f"{size_bytes / 1024:.2f} KB ({size_bytes:,} Bytes)"
    elif size_bytes < 1024 * 1024 * 1024:
        return f"{size_bytes / (1024 * 1024):.2f} MB ({size_bytes:,} Bytes)"
    else:
        return f"{size_bytes / (1024 * 1024 * 1024):.2f} GB ({size_bytes:,} Bytes)"


def find_duplicates(directory):
    """
    Traverse a directory recursively and identify all duplicate files by SHA-256 hash.

    Parameters:
        directory (str): The root directory to scan.

    Returns:
        dict: Summary dictionary containing scan results and duplicate groups.
    """
    hash_map = {}
    inaccessible_files = []
    scanned_count = 0

    for current_root, _, filenames in os.walk(directory):
        for filename in filenames:
            full_path = os.path.join(current_root, filename)
            scanned_count += 1

            file_hash = calculate_hash(full_path)
            if file_hash is None:
                inaccessible_files.append(full_path)
                continue

            if file_hash not in hash_map:
                hash_map[file_hash] = []
            hash_map[file_hash].append(full_path)

    duplicate_groups = {}
    total_duplicates = 0
    wasted_bytes = 0

    for file_hash, file_paths in hash_map.items():
        if len(file_paths) > 1:
            duplicate_groups[file_hash] = file_paths
            redundant_count = len(file_paths) - 1
            total_duplicates += redundant_count

            try:
                single_copy_size = os.path.getsize(file_paths[0])
            except (OSError, FileNotFoundError):
                single_copy_size = 0
            wasted_bytes += redundant_count * single_copy_size

    return {
        "scanned_count": scanned_count,
        "duplicate_groups": duplicate_groups,
        "total_duplicates": total_duplicates,
        "wasted_bytes": wasted_bytes,
        "inaccessible_files": inaccessible_files,
    }


def display_results(results, target_directory):
    """
    Format and output the duplicate scan results to standard output.

    Parameters:
        results (dict): The result dictionary generated by find_duplicates().
        target_directory (str): The path of the scanned directory.
    """
    separator = "=" * 75
    print("\n" + separator)
    print("                DUPLICATE FILE DETECTION AUDIT REPORT")
    print(separator)
    print(f"Target Directory     : {target_directory}")
    print(f"Total Files Scanned  : {results['scanned_count']}")
    print(f"Inaccessible Files   : {len(results['inaccessible_files'])}")
    print(f"Duplicate Groups     : {len(results['duplicate_groups'])}")
    print(f"Total Duplicate Files: {results['total_duplicates']}")
    print(f"Wasted Storage Space : {format_storage_size(results['wasted_bytes'])}")
    print(separator)

    if results["inaccessible_files"]:
        print("\n[!] WARNING: Inaccessible Files (Read/Permission Error):")
        for index, inacc_file in enumerate(results["inaccessible_files"], start=1):
            print(f"    {index}. {inacc_file}")

    if not results["duplicate_groups"]:
        print("\n[+] SUCCESS: No duplicate files found in the specified directory.")
        print(separator + "\n")
        return

    print("\n[+] DUPLICATE FILE GROUPS FOUND:\n")
    group_index = 1
    for file_hash, file_list in results["duplicate_groups"].items():
        try:
            file_size_bytes = os.path.getsize(file_list[0])
            size_label = format_storage_size(file_size_bytes)
        except (OSError, FileNotFoundError):
            size_label = "Unavailable"

        print(f"Group #{group_index}:")
        print(f"  SHA-256 Digest : {file_hash}")
        print(f"  Individual Size: {size_label}")
        print(f"  Total Copies   : {len(file_list)}")
        print(f"  --> [Original] : {file_list[0]}")
        for dup_index, dup_path in enumerate(file_list[1:], start=1):
            print(f"  --> [Duplicate {dup_index}]: {dup_path}")
        print("-" * 75)
        group_index += 1

    print("\nAUDIT SUMMARY:")
    print(f"Found {results['total_duplicates']} redundant duplicate file(s) across {len(results['duplicate_groups'])} distinct group(s).")
    print(f"Reclaimable storage space: {format_storage_size(results['wasted_bytes'])}.")
    print("Security Guarantee: No files were modified or deleted.")
    print(separator + "\n")
